# Arithmetics: +, -, *, /, %, //, **

print("The sum of 3 and 4 is", 3 + 4)
print("The difference of 3 and 4 is", 3 - 4)
print("The product of 3 and 4 is", 3 * 4)
print("The division of 3 and 4 is", 3 / 4)
print("The remainder of 4 by 3 is", 4 % 3)
print("The power of 3 by 4", 3 ** 4)
print("The floor division  of 4 by 3 is", 4 // 3)